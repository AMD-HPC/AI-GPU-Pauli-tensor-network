"""
extract_noise_ptm.py — Extract noise PTMs from heavy_hex JSON and generate C++ arrays.

Reads heavy_hex_3x3_gamma{...}_hardware.json and produces C++ code for
embedding noise PTMs directly in heavyhex.hpp as static arrays.

Usage:
  python3 extract_noise_ptm.py [path/to/noise.json] [output.cpp]

Output: C++ snippet with static float arrays, one 16×16 PTM per bond per gamma.

The PTM layout matches CppSim's col-major convention:
  PTM[row + 16*col]  where row=output Pauli, col=input Pauli
  Basis: I=0, X=1, Y=2, Z=3, index = site1*4 + site2
"""

import json
import sys
import re
import os

NOISE_JSON = sys.argv[1] if len(sys.argv) > 1 else \
    "/scratch/paolod/QC/amd-TensorNetworkQuantumSimulator.jl/data/noise/heavy_hex_3x3_gamma1.00-1.40-1.80_hardware.json"

OUT_FILE = sys.argv[2] if len(sys.argv) > 2 else "heavyhex_noise_data.hpp"

# Load the JSON
with open(NOISE_JSON) as f:
    data = json.load(f)

gammas = sorted(data.keys(), key=float)  # ['1.0', '1.4', '1.8']
print(f"Gammas: {gammas}")

# Parse edge key "(v1,) => (v2,)" → (v1-1, v2-1) 0-based
def parse_edge(key):
    m = re.findall(r'\((\d+),\)', key)
    return int(m[0])-1, int(m[1])-1  # Julia 1-based → 0-based

# Build edge→bond_id map from our known edge list
# (must match HEAVY_HEX_3x3_EDGES in heavyhex.hpp)
# Load edge list from our heavyhex.hpp data
EDGES = [
    (0,30),(0,31),(1,30),(1,32),(2,32),(2,33),(2,34),(3,33),(3,35),
    (4,35),(4,36),(4,37),(5,36),(5,38),(6,38),(6,39),(7,40),(7,41),
    (8,31),(8,42),(9,42),(9,43),(9,44),(10,34),(10,43),(10,45),
    (11,45),(11,46),(11,47),(12,37),(12,46),(12,48),(13,48),(13,49),(13,50),
    (14,39),(14,49),(14,51),(15,51),(15,52),(16,53),(16,54),
    (17,44),(17,53),(17,55),(18,55),(18,56),(18,57),(19,47),(19,56),(19,58),
    (20,58),(20,59),(20,60),(21,50),(21,59),(21,61),(22,40),(22,61),(22,62),
    (23,52),(23,62),(24,54),(24,63),(25,63),(25,64),(26,57),(26,64),(26,65),
    (27,65),(27,66),(28,60),(28,66),(28,67),(29,41),(29,67),
]
edge_to_bond = {(u,v): i for i, (u,v) in enumerate(EDGES)}
edge_to_bond.update({(v,u): i for i, (u,v) in enumerate(EDGES)})

n_bonds = len(EDGES)
print(f"Bonds: {n_bonds}")

# For each gamma, collect PTMs indexed by bond_id
# PTM from JSON is row-major [16][16]: PTM[input_col][output_row]
# We need col-major [256]: M[row + 16*col]
def to_colmajor(ptm_rowmajor):
    """Convert PTM from JSON format to CppSim col-major flat [256].

    JSON stores PTM as ptm[output_row][input_col] (Schrödinger picture, row-major).
    Julia transposes before use: itensor(transpose(ptm), legs).
    This gives the ADJOINT channel (Heisenberg picture): PTM_H = PTM_S^T.

    CppSim operates in Heisenberg picture, so we must also transpose:
    PTM_H[output_row][input_col] = PTM_S[input_col][output_row]

    CppSim col-major: out[output_row + 16*input_col] = PTM_H[output_row][input_col]
    = PTM_S[input_col][output_row]
    """
    out = [0.0] * 256
    for output_row in range(16):
        for input_col in range(16):
            # Transpose: swap row/col from JSON
            out[output_row + 16*input_col] = ptm_rowmajor[input_col][output_row]
    return out

gamma_ptms = {}  # gamma_str → list of 256 floats per bond_id

for gamma_str in gammas:
    layers = data[gamma_str]
    bond_ptms = [None] * n_bonds  # one PTM per bond

    for layer_idx, layer_data in layers.items():
        for edge_key, ptm in layer_data.items():
            u, v = parse_edge(edge_key)
            bond_id = edge_to_bond.get((u,v))
            if bond_id is None:
                print(f"  WARNING: edge ({u},{v}) not found in bond list")
                continue
            if bond_ptms[bond_id] is not None:
                print(f"  WARNING: bond {bond_id} has multiple PTMs (layer {layer_idx})")
            bond_ptms[bond_id] = to_colmajor(ptm)

    # Check all bonds covered
    missing = [i for i, p in enumerate(bond_ptms) if p is None]
    if missing:
        print(f"  WARNING: gamma={gamma_str} missing PTMs for bonds: {missing}")

    gamma_ptms[gamma_str] = bond_ptms
    print(f"  gamma={gamma_str}: {n_bonds - len(missing)}/{n_bonds} PTMs loaded")

# Generate C++ output
def gamma_to_cname(g):
    return g.replace('.', '_')  # "1.0" → "1_0"

lines = []
lines.append("// heavyhex_noise_data.hpp — auto-generated by extract_noise_ptm.py")
lines.append("// DO NOT EDIT — regenerate from the noise JSON if PTMs change")
lines.append("//")
lines.append(f"// Source: {os.path.basename(NOISE_JSON)}")
lines.append(f"// Gammas: {', '.join(gammas)}")
lines.append(f"// Bonds: {n_bonds}")
lines.append("// PTM layout: col-major [256], basis I=0,X=1,Y=2,Z=3, index=site1*4+site2")
lines.append("")
lines.append("#pragma once")
lines.append("#include <array>")
lines.append("")
lines.append(f"static constexpr int HEAVY_HEX_3x3_N_GAMMA = {len(gammas)};")
lines.append(f"static constexpr float HEAVY_HEX_3x3_GAMMAS[{len(gammas)}] = {{{', '.join(f'{float(g):.1f}f' for g in gammas)}}};")
lines.append("")

for gamma_str in gammas:
    cname = gamma_to_cname(gamma_str)
    bond_ptms = gamma_ptms[gamma_str]
    lines.append(f"// Noise PTMs for gamma={gamma_str}")
    lines.append(f"// Each row: 256 floats = 16x16 col-major PTM for one bond")
    lines.append(f"static const float HEAVY_HEX_3x3_NOISE_GAMMA{cname}[{n_bonds}][256] = {{")
    for bond_id, ptm in enumerate(bond_ptms):
        if ptm is None:
            ptm = [0.0] * 256
        # Format as 16 groups of 16 for readability
        vals = ', '.join(f'{v:.8f}f' for v in ptm)
        u, v = EDGES[bond_id]
        lines.append(f"    /* bond {bond_id:2d} ({u:2d},{v:2d}) */ {{{vals}}},")
    lines.append("};")
    lines.append("")

# Lookup function
lines.append("// Get noise PTM for a given bond_id and gamma value (nearest match)")
lines.append("inline const float* heavy_hex_3x3_noise_ptm(int bond_id, float gamma) {")
lines.append("    // Find nearest gamma")
lines.append("    int best = 0;")
lines.append("    float best_diff = fabsf(gamma - HEAVY_HEX_3x3_GAMMAS[0]);")
lines.append(f"    for (int i = 1; i < HEAVY_HEX_3x3_N_GAMMA; i++) {{")
lines.append("        float diff = fabsf(gamma - HEAVY_HEX_3x3_GAMMAS[i]);")
lines.append("        if (diff < best_diff) { best = i; best_diff = diff; }")
lines.append("    }")
for i, gamma_str in enumerate(gammas):
    cname = gamma_to_cname(gamma_str)
    if i == 0:
        lines.append(f"    if (best == 0) return HEAVY_HEX_3x3_NOISE_GAMMA{cname}[bond_id];")
    elif i == len(gammas)-1:
        lines.append(f"    return HEAVY_HEX_3x3_NOISE_GAMMA{cname}[bond_id];")
    else:
        lines.append(f"    if (best == {i}) return HEAVY_HEX_3x3_NOISE_GAMMA{cname}[bond_id];")
lines.append("}")
lines.append("")

with open(OUT_FILE, 'w') as f:
    f.write('\n'.join(lines))

print(f"\nWritten: {OUT_FILE}")
print(f"Size: {os.path.getsize(OUT_FILE)/1e6:.1f} MB")
print(f"\nUsage in C++:")
print(f"  #include \"{OUT_FILE}\"")
print(f"  const float* ptm = heavy_hex_3x3_noise_ptm(bond_id, 1.0f);")
print(f"  gate_ops.apply_binary_gate(..., ptm, ...);")
